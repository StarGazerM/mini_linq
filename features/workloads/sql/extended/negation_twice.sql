WITH
  A AS (SELECT DISTINCT c0 FROM "mini-linq/raw/0"),
  B AS (SELECT DISTINCT c0,c1 FROM "mini-linq/raw/1"),
  C AS (SELECT DISTINCT c0,c1 FROM "mini-linq/raw/2")
SELECT DISTINCT * FROM (
SELECT A.c0 FROM A WHERE NOT EXISTS (SELECT 1 FROM B WHERE B.c0=A.c0) AND NOT EXISTS (SELECT 1 FROM C WHERE C.c0=A.c0)
) AS result
ORDER BY 1;
