WITH
  A AS (SELECT DISTINCT c0 FROM "mini-linq/raw/0"),
  S AS (SELECT DISTINCT c0,c1,c2 FROM "mini-linq/raw/1")
SELECT DISTINCT * FROM (
SELECT A.c0,COALESCE((SELECT DISTINCT S.c1 FROM S WHERE S.c0=A.c0),0) AS v
FROM A WHERE COALESCE((SELECT DISTINCT S.c1 FROM S WHERE S.c0=A.c0),0)>2
) AS result
ORDER BY 1,2;
