#!/usr/bin/env python3
"""Translate the authored SRDatalog DOOP DSL, without optimizer rewrites.

Only multihead expansion changes rule structure. Declaration/body ordering,
negation, wildcard arguments and filters are retained. Dataset constants are
symbolic host fields, never values baked in from a particular corpus.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path


def ident(name: str) -> str:
    return "r_" + name.lower()


def tuple_type(arity: int) -> str:
    return "(" + "i32, " * arity + ")"


def generate(repo: Path, field_flow: bool, output: Path) -> None:
    source = repo / "examples/doop.py"
    text = source.read_text()
    tree = ast.parse(text)
    builder = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "build_doopdb_program")
    keys = sorted({n.slice.value for n in ast.walk(builder)
                   if isinstance(n, ast.Subscript) and isinstance(n.value, ast.Name)
                   and n.value.id == "meta" and isinstance(n.slice, ast.Constant)
                   and isinstance(n.slice.value, str)})
    # Distinct sentinel integers preserve identity even when real metadata aliases.
    meta = {key: 1900000000 + i for i, key in enumerate(keys)}
    constants = {value: "constants.c_" + key.lower() for key, value in meta.items()}
    sys.path.insert(0, str(repo / "src"))
    sys.path.insert(0, str(repo))
    from srdatalog.dsl import ArgKind, Atom, Filter, Negation
    spec = importlib.util.spec_from_file_location("srd_doop_source", source)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    program = module.build_doopdb_program(meta, field_flow=field_flow)
    relations = program.relations
    inputs = [r for r in relations if r.input_file]
    outputs = [r for r in relations if not r.input_file]
    if len({ident(r.name) for r in relations}) != len(relations):
        raise ValueError("Relation names collide after Rust normalization")
    for rel in relations:
        if any(t is not int for t in rel.column_types):
            raise ValueError(f"{rel.name}: unsupported non-integer column")

    def arg(a, head=False):
        if a.kind == ArgKind.LVAR:
            if a.var_name == "_":
                if head:
                    raise ValueError("Wildcard in head")
                return "_"
            return ("*" if head else "") + "v_" + a.var_name
        if a.kind == ArgKind.CONST:
            if a.const_cpp_expr != str(a.const_value):
                raise ValueError(f"Unsupported constant expression {a.const_cpp_expr}")
            return constants.get(a.const_value, str(a.const_value) + "i32")
        raise ValueError(f"Unsupported argument {a}")

    def atom(a, head=False):
        return ident(a.rel) + "(" + ", ".join(arg(x, head) for x in a.args) + ")"

    def clause(c):
        if isinstance(c, Atom):
            return atom(c)
        if isinstance(c, Negation):
            return "!" + atom(c.atom)
        if isinstance(c, Filter):
            # This query's C++ predicates are conjunctions of integer inequalities.
            match = re.fullmatch(r"\s*return\s+(.+);\s*", c.code)
            if not match:
                raise ValueError(f"Unsupported filter {c.code!r}")
            parts = []
            for part in match[1].split("&&"):
                m = re.fullmatch(r"\s*([A-Za-z_]\w*|-?\d+)\s*(!=|==|<=|>=|<|>)\s*([A-Za-z_]\w*|-?\d+)\s*", part)
                if not m:
                    raise ValueError(f"Unsupported filter expression {part!r}")
                def operand(value):
                    if re.fullmatch(r"-?\d+", value):
                        return constants.get(int(value), value + "i32")
                    if value not in c.vars:
                        raise ValueError(f"Unbound filter operand {value!r}")
                    return "*v_" + value
                parts.append(f"{operand(m[1])} {m[2]} {operand(m[3])}")
            return "if " + " && ".join(parts)
        raise ValueError(f"Unsupported body construct {type(c).__name__}: {c!r}")

    lines = ["// Generated by translate.py; do not edit.",
             f"// examples/doop.py sha256: {hashlib.sha256(text.encode()).hexdigest()}",
             f"// field_flow={str(field_flow).lower()}, {len(program.rules)} source rules, {len(inputs)} inputs, {len(outputs)} IDBs.",
             "#[derive(Clone, Debug, Default)]", "pub struct SrdConstants {"]
    lines += [f"    pub c_{key.lower()}: i32," for key in keys]
    lines += ["}", "impl SrdConstants {", "    fn load(meta: &std::collections::BTreeMap<String, i32>) -> crate::Result<Self> {", "        Ok(Self {"]
    lines += [f'            c_{key.lower()}: *meta.get("{key}").ok_or("Missing metadata key: {key}")?,' for key in keys]
    lines += ["        })", "    }", "}", "#[derive(Clone, Debug, Default)]", "pub struct SrdFacts {", "    pub constants: SrdConstants,"]
    lines += [f"    pub {ident(r.name)}: Vec<{tuple_type(r.arity)}>," for r in inputs]
    lines += ["}", "impl SrdFacts {", "    pub fn load(dir: &std::path::Path) -> crate::Result<Self> {", '        let meta = serde_json::from_reader(std::fs::File::open(dir.join("meta.json"))?)?;', "        let constants = SrdConstants::load(&meta)?;", "        Ok(Self {", "            constants,"]
    for r in inputs:
        values = "".join(f"row[{i}], " for i in range(r.arity))
        lines.append(f'            {ident(r.name)}: crate::load_rows::<{r.arity}, _>(&dir.join("{r.input_file}"), |row| ({values}))?,')
    lines += ["        })", "    }", "}", "#[derive(Debug, Default, PartialEq, Eq)]", "pub struct SrdResults {"]
    lines += [f"    pub {ident(r.name)}: Vec<{tuple_type(r.arity)}>," for r in outputs]
    lines += ["}", "impl SrdResults {", "    pub fn counts(&self) -> std::collections::BTreeMap<String, usize> {", "        std::collections::BTreeMap::from(["]
    lines += [f'            ("{r.name}".into(), self.{ident(r.name)}.len()),' for r in outputs]
    lines += ["        ])", "    }", "    pub fn export(&self, dir: &std::path::Path) -> crate::Result<()> {", "        std::fs::create_dir_all(dir)?;"]
    for r in outputs:
        values = ", ".join(f"row.{i}" for i in range(r.arity))
        lines.append(f'        crate::export_rows(&dir.join("{r.name}.csv"), self.{ident(r.name)}.iter().map(|row| [{values}]))?;')
    lines += ["        Ok(())", "    }", "}", "#[macro_export]", "macro_rules! srd_doop_engine {", "    ($name:ident, pipeline { $($pipeline:tt)* }) => {", "        #[allow(non_snake_case, unused_variables)]", "        pub fn $name(facts: $crate::SrdFacts) -> $crate::SrdResults {", "            let constants = facts.constants;", "            let (" + ", ".join(ident(r.name) for r in outputs) + ",) = cq_datalog::datalog! {", "                pipeline { $($pipeline)* }", "                struct SrdDoop;"]
    for r in relations:
        columns = ", ".join(f"c{i}: i32" for i in range(r.arity))
        initializer = f" = (facts.{ident(r.name)})" if r.input_file else ""
        lines.append(f"                relation {ident(r.name)}({columns}){initializer};")
    lines.append("                output " + ", ".join(ident(r.name) for r in outputs) + ";")
    for rule in program.rules:
        try:
            body = ", ".join(clause(c) for c in rule.body)
            lines.append(f"                // {rule.name}")
            lines.extend(f"                {atom(h, True)} :- {body};" for h in rule.heads)
        except ValueError as error:
            raise ValueError(f"{source}: rule {rule.name}: {error}") from error
    lines += ["            };", "            $crate::SrdResults {"]
    lines += [f"                {ident(r.name)}: {ident(r.name)}.collect()," for r in outputs]
    lines += ["            }", "        }", "    };", "}", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    schema = {"source_sha256": hashlib.sha256(text.encode()).hexdigest(), "field_flow": field_flow,
              "source_rules": len(program.rules), "expanded_rules": sum(len(r.heads) for r in program.rules),
              "inputs": {r.name: {"arity": r.arity, "file": r.input_file} for r in inputs},
              "outputs": {r.name: r.arity for r in outputs}, "metadata_keys": keys}
    output.with_suffix(".schema.json").write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--srd-repo", type=Path, required=True)
    parser.add_argument("--field-flow", action="store_true")
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "src/generated.rs")
    args = parser.parse_args()
    generate(args.srd_repo.resolve(), args.field_flow, args.output)
